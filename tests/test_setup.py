def test_existing_config_is_backed_up_before_overwrite(tmp_path, monkeypatch):
    path = tmp_path / "cvebeacon.toml"
    path.write_text("# old configuration\n[inventory]\npath = 'old.csv'\n", encoding="utf-8")
    write_inventory(tmp_path)
    feed(monkeypatch, ["y", *watch_answers()])
    assert run_setup(path, now=NOW) == 0
    backups = list(tmp_path.glob("cvebeacon.toml.bak-*"))
    assert len(backups) == 1
    assert backups[0].read_text(encoding="utf-8").startswith("# old configuration")
    assert path.read_text(encoding="utf-8").startswith("# Generated by cvebeacon setup")


