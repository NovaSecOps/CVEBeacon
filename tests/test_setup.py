@pytest.mark.parametrize(
    "selection,extra,expected",
    [
        ("1", ["", "", "", ""], "cvss"),
        ("2", ["", "", "", ""], "epss"),
        ("3", ["", "", ""], "kev"),
        ("4", ["", "", "", "", ""], "kev"),
        ("5", ["", "", ""], "exploitation"),
    ],
)
def test_rule_presets(tmp_path, monkeypatch, selection, extra, expected):
    write_inventory(tmp_path)
    rule = [selection, *extra]
    assert run_watch(tmp_path, monkeypatch, rule=rule) == 0
    config = load_config(tmp_path / "cvebeacon.toml")
    assert len(config.watch.rules) == 1
    assert expected in describe_condition(config.watch.rules[0].condition)


def test_custom_rule_or_choice_and_vendor_filter(tmp_path, monkeypatch):
    write_inventory(tmp_path)
    rule = ["6", "8", "0.4", "or", "n", "custom", "Acme, Beta", "alert"]
    assert run_watch(tmp_path, monkeypatch, rule=rule) == 0
    config = load_config(tmp_path / "cvebeacon.toml")
    rule_value = config.watch.rules[0]
    assert rule_value.name == "custom"
    assert rule_value.old_cves == "alert"
    condition = rule_value.condition
    assert condition.kind == "all"
    assert any(child.kind == "any" for child in condition.children)
    description = describe_condition(condition)
    assert "OR" in description
    assert "vendor in [Acme, Beta]" in description


