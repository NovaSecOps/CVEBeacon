NOW = datetime(2026, 11, 4, 12, 0)
WATCH_START = ["", "", "", "", "", "", ""]  # mode, four sources, initial, NVD key
CRITICAL_RULE = ["", "", "", "", ""]  # selection, CVSS, name, vendor, old_cves
WEBHOOK_CHANNEL = ["", "10", "https://example.org/cvebeacon", "", "n"]
SCHEDULE_NO = ["", "", "n"]  # type, times, install
SCHEDULE_BOTH_NO = ["", "", "", "n"]  # type, times, command, install
TAIL = ["", "n"]  # rule channels, test send


def write_inventory(tmp_path: Path) -> Path:
    path = tmp_path / "inventory.csv"
    path.write_text("asset_id,vendor,product,version\na,Acme,Widget,1\n", encoding="utf-8")
    return path


def feed(monkeypatch, answers, secrets=()):
    values = iter(answers)
    secret_values = iter(secrets)
    monkeypatch.setattr("builtins.input", lambda _message="": next(values))
    monkeypatch.setattr("getpass.getpass", lambda _message="": next(secret_values))


def watch_answers(rule=None, channel=None, schedule=None):
    return [
        *WATCH_START,
        *(CRITICAL_RULE if rule is None else rule),
        *(WEBHOOK_CHANNEL if channel is None else channel),
        *TAIL,
        *(SCHEDULE_NO if schedule is None else schedule),
    ]


def run_watch(tmp_path, monkeypatch, rule=None, channel=None, schedule=None, answers=None, secrets=()):
    feed(
        monkeypatch,
        watch_answers(rule, channel, schedule) if answers is None else answers,
        secrets,
    )
    return run_setup(tmp_path / "cvebeacon.toml", now=NOW)


def test_watch_setup_writes_a_loadable_commented_config(tmp_path, monkeypatch, capsys):
    write_inventory(tmp_path)
    assert run_watch(tmp_path, monkeypatch) == 0
    path = tmp_path / "cvebeacon.toml"
    text = path.read_text(encoding="utf-8")
    assert text.startswith("# Generated by cvebeacon setup on 2026-11-04.")
    assert "# Watch mode" in text
    assert "# Alert delivery channel. See docs/WATCH.md." in text
    assert "# Alert rule. See docs/WATCH.md." in text
    config = load_config(path)
    assert config.watch.enabled is True
    assert config.watch.sources == ("nvd", "euvd", "cisa_kev", "eu_kev", "epss")
    assert [rule.name for rule in config.watch.rules] == ["critical"]
    assert describe_condition(config.watch.rules[0].condition) == "cvss >= 9.0"
    assert [(channel.name, channel.type) for channel in config.watch.channels] == [
        ("alerts", "webhook")
    ]
    assert cli.main(["--config", str(path), "watch", "rules", "check"]) == 0
    output = capsys.readouterr().out
    assert "critical: cvss >= 9.0" in output


