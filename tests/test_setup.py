def test_nvd_key_can_be_stored_in_a_secret_file(tmp_path, monkeypatch):
    write_inventory(tmp_path)
    answers = watch_answers()
    answers[6] = "file"  # replace the NVD key choice
    feed(monkeypatch, answers, ["nvd-canary"])
    assert run_setup(tmp_path / "cvebeacon.toml", now=NOW) == 0
    text = (tmp_path / "cvebeacon.toml").read_text(encoding="utf-8")
    expected_file = "secrets/nvd-api-key" if os.name == "posix" else "nvd-api-key"
    assert f'nvd_api_key_file = "{expected_file}"' in text
    assert "nvd-canary" not in text
    secret_path = tmp_path / expected_file
    assert secret_path.read_text(encoding="utf-8") == "nvd-canary"
    config = load_config(tmp_path / "cvebeacon.toml")
    assert config.sources.nvd_api_key_file == secret_path.resolve()
    assert config.nvd_api_key() == "nvd-canary"


