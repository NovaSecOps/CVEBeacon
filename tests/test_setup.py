@pytest.mark.skipif(os.name != "posix", reason="POSIX permission check")
def test_secret_file_permissions_and_no_echo(tmp_path, monkeypatch, capsys):
    write_inventory(tmp_path)
    channel = ["", "1", "custom", "", "", "", "", "", "user", "file", "n"]
    assert run_watch(tmp_path, monkeypatch, channel=channel, secrets=["canary-secret"]) == 0
    path = tmp_path / "cvebeacon.toml"
    text = path.read_text(encoding="utf-8")
    secret_path = tmp_path / "secrets" / "alerts-password"
    assert secret_path.read_text(encoding="utf-8") == "canary-secret"
    assert stat.S_IMODE(secret_path.stat().st_mode) == 0o600
    assert stat.S_IMODE(secret_path.parent.stat().st_mode) == 0o700
    assert 'password_file = "secrets/alerts-password"' in text
    assert "canary-secret" not in text
    assert "canary-secret" not in capsys.readouterr().out
    load_config(path)


